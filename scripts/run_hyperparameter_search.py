"""
Run hyperparameter search for image-based risk regression models.

This script searches learning rate and weight decay values for ResNet-18 and
ViT-Tiny before final multi-seed training. It expects the dataset generated by
the simulation pipeline:

    data/generated_dataset/
        trial_summary_all.csv
        layout_images/

Only clean-success trials are used for model selection. Splits are made at the
layout level to prevent image variants from the same layout appearing in both
training and validation data.
"""

